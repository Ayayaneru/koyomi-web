/** 某一天是不是节气；不是就返回 null */
export function solarTermOf(ts: number): string | null {
  const d = new Date(ts)
  const days = TABLE[d.getFullYear()]
  if (!days) return null
  const month = d.getMonth() + 1
  const day = d.getDate()
  const index = (month - 1) * 2
  if (days[index] === day) return SOLAR_TERM_NAMES[index]
  if (days[index + 1] === day) return SOLAR_TERM_NAMES[index + 1]
  return null
}
